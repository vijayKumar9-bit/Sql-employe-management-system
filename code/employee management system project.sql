-- 1. EMPLOYEE INSIGHTS
-- 1. HOW MANY UNIQUE EMPLOYEE ARE CUNRRENTLY IN THE SYSTEM?

SELECT COUNT(DISTINCT EMP_ID) AS TOTAL_EMPLOYEES
FROM EMPLOYEE;

-- 2.WHICH DEPARTMNET HAVE THE HIGHEST NUMBER OF EMPLOYEES?
SELECT JD.JOBDEPT,
COUNT(E.EMP_ID) AS EMPLOYEE_COUNT
FROM EMPLOYEE E
JOIN JOBDEPARTMENT JD
ON E.JOB_ID = JD.JOB_ID
GROUP BY JD.JOBDEPT
ORDER BY EMPLOYEE_COUNT DESC;

-- 3.WHAT IS THE AVERAGE SALARY OF EMPLOYEES BY DEPARTMENT?
SELECT JD.JOBDEPT,
	   AVG(SB.AMOUNT) AS AVERAGE_SALARY
FROM EMPLOYEE E
JOIN JOBDEPARTMENT JD
ON E.JOB_ID = JD.JOB_ID
JOIN SALARYBONUS SB
ON JD.JOB_ID = SB.JOB_ID
GROUP BY JD.JOBDEPT;

-- 4. WHO ARE THE TOP 5 HIGHEST_PAID EMPLOYEES?
SELECT E.EMP_ID,
	   E.FIRSTNAME,
       E.LASTNAME,
       JD.JOBDEPT,
       SB.AMOUNT AS SALARY
