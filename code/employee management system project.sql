LIMIT 1;

-- 2.WHAT IS THE AVERAGE NUMBER OF LEAVE DAYS TAKEN BY ITS EMPLOYEES PER DEPARTMENT?
SELECT 
    JD.JOBDEPT,
    COUNT(L.LEAVE_ID) / COUNT(DISTINCT E.EMP_ID) AS AVERAGE_LEAVE_DAYS
FROM EMPLOYEE E
JOIN JOBDEPARTMENT JD
ON E.JOB_ID = JD.JOB_ID
LEFT JOIN LEAVES L
ON E.EMP_ID = L.EMP_ID
GROUP BY JD.JOBDEPT;

-- 3.WHICH EMPLOYEES HAVE TAKEN THE MOST LEAVES?
SELECT 
    E.EMP_ID,
    E.FIRSTNAME,
    E.LASTNAME,
    COUNT(L.LEAVE_ID) AS TOTAL_LEAVES
FROM EMPLOYEE E
JOIN LEAVES L
ON E.EMP_ID = L.EMP_ID
GROUP BY E.EMP_ID, E.FIRSTNAME, E.LASTNAME
HAVING COUNT(L.LEAVE_ID) = (
    SELECT MAX(LEAVE_COUNT)
    FROM (
        SELECT COUNT(LEAVE_ID) AS LEAVE_COUNT
        FROM LEAVES
        GROUP BY EMP_ID
    ) AS TEMP
);

-- 4. WHAT IS THE TOTAL NUMBER OF LEAVE DAYS TAKLEN COMAPANY-WIDE?
SELECT COUNT(*) AS TOTAL_LEAVE_DAYS
FROM LEAVES;

-- 5.HOW DO LEAVE DAYS CORRELATE WITH PAYROLL AMOUNTS?
SELECT e.emp_ID,
       e.firstname,
       COUNT(l.leave_ID) AS total_leaves,
       AVG(p.total_amount) AS average_payroll
FROM Employee e
LEFT JOIN Leaves l
ON e.emp_ID = l.emp_ID
LEFT JOIN Payroll p
ON e.emp_ID = p.emp_ID
GROUP BY e.emp_ID, e.firstname
ORDER BY total_leaves DESC;

