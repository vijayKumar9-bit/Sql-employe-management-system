-- 3. LEAVE AND ABSENECE PATTERNS
-- 1.WHICH YEAR HAD THE MOST EMPLOYEES TAKING LEAVES?
SELECT YEAR(DATE) AS LEAVE_YEAR,
COUNT(DISTINCT EMP_ID) AS TOTAL_EMPLOYEES
FROM LEAVES
